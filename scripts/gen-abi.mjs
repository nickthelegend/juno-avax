// Writes sdk/src/abi.ts from the Foundry build output (run `forge build` in contracts/ first).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (name) => JSON.parse(readFileSync(join(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8')).abi;
const out = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.\n` +
  `export const factoryAbi = ${JSON.stringify(read('JunoFactory'), null, 2)} as const;\n\n` +
  `export const postAbi = ${JSON.stringify(read('JunoPost'), null, 2)} as const;\n`;
writeFileSync(join(root, 'sdk/src/abi.ts'), out);
console.log('wrote sdk/src/abi.ts');
