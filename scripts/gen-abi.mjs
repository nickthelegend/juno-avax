// Writes sdk/src/abi.ts and sdk/src/eerc-abi.ts from the Foundry build output
// (run `forge build` and `FOUNDRY_PROFILE=eerc forge build` in contracts/ first).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (name, out = 'out') => JSON.parse(readFileSync(join(root, 'contracts', out, `${name}.sol`, `${name}.json`), 'utf8')).abi;
const out = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.\n` +
  `export const factoryAbi = ${JSON.stringify(read('JunoFactory'), null, 2)} as const;\n\n` +
  `export const postAbi = ${JSON.stringify(read('JunoPost'), null, 2)} as const;\n\n` +
  `export const gasStationAbi = ${JSON.stringify(read('JunoGasStation'), null, 2)} as const;\n`;
writeFileSync(join(root, 'sdk/src/abi.ts'), out);
console.log('wrote sdk/src/abi.ts');
if (existsSync(join(root, 'contracts/out-eerc'))) {
  // Upstream declares most errors in a shared file, so a contract's own ABI can miss errors it reverts with.
  // Collect every eERC/OpenZeppelin error once and add them to both ABIs, so reverts decode by name.
  const { readdirSync } = await import('node:fs');
  const errors = new Map();
  for (const dir of readdirSync(join(root, 'contracts/out-eerc'))) {
    if (!dir.endsWith('.sol')) continue;
    for (const f of readdirSync(join(root, 'contracts/out-eerc', dir))) {
      for (const e of JSON.parse(readFileSync(join(root, 'contracts/out-eerc', dir, f), 'utf8')).abi ?? []) {
        if (e.type === 'error' && !/^ERC(721|1155)/.test(e.name)) errors.set(`${e.name}(${e.inputs.map((i) => i.type)})`, e);
      }
    }
  }
  const withErrors = (abi) => [...abi.filter((e) => e.type !== 'error'), ...errors.values()];
  const eerc = `// Generated by scripts/gen-abi.mjs from contracts/out-eerc (Ava Labs EncryptedERC, pinned submodule). Do not edit by hand.\n` +
    `export const encryptedErcAbi = ${JSON.stringify(withErrors(read('EncryptedERC', 'out-eerc')))} as const;\n\n` +
    `export const registrarAbi = ${JSON.stringify(withErrors(read('Registrar', 'out-eerc')))} as const;\n`;
  writeFileSync(join(root, 'sdk/src/eerc-abi.ts'), eerc);
  console.log('wrote sdk/src/eerc-abi.ts');
}
