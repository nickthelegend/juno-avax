// Writes web/lib/deployment.ts from deployments/fuji.json so the app can cite recorded evidence.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const d = JSON.parse(readFileSync(join(root, 'deployments/fuji.json'), 'utf8'));
const out = {
  factory: d.factory.address,
  factoryTx: d.factory.deployTx,
  medianMs: d.seedStats?.confirmMsMedian ?? null,
  blockMedianMs: d.seedStats?.blockMsMedian ?? null,
  measuredTxs: d.seedStats?.measured ?? null,
  // The seeded test accounts, so the feed can say "mira" instead of 0xB9F0…0037.
  names: d.accounts ? Object.fromEntries(Object.entries(d.accounts).filter(([name]) => ['mira', 'kai', 'oto'].includes(name)).map(([name, address]) => [address, name])) : {},
};
writeFileSync(join(root, 'web/lib/deployment.ts'), `// Generated by scripts/gen-deployment.mjs from deployments/fuji.json. Do not edit by hand.\nexport const DEPLOYMENT = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log('wrote web/lib/deployment.ts', out);
